        contactForm: function () {
            $('.rwt-dynamic-form').on('submit', function (e) {
				e.preventDefault();
				var form = this;
				var btn = form.querySelector('button[type="submit"]');
				var btnText = btn.querySelector('.btn-text');
				var btnLoading = btn.querySelector('.btn-loading');
				var toast = document.getElementById('contact-toast');

				// Show loading state
				btn.setAttribute('disabled', 'disabled');
				if (btnText) btnText.style.display = 'none';
				if (btnLoading) btnLoading.style.display = 'inline';

				// Hide any previous toast
				if (toast) toast.style.display = 'none';

				// Send via FormSubmit AJAX endpoint
				var formData = new FormData(form);

				fetch(form.action, {
					method: 'POST',
					body: formData,
					headers: { 'Accept': 'application/json' }
				})
				.then(function (response) {
					if (response.ok) {
						return response.json();
					}
					throw new Error('Network response was not ok');
				})
				.then(function (data) {
					// Success
					if (toast) {
						toast.className = 'contact-toast contact-toast-success';
						toast.innerHTML = '<span class="toast-icon">✅</span> Message sent successfully! I\'ll respond within 24 hours.';
						toast.style.display = 'flex';
					}
					form.reset();
					// Remove focused class from form groups
					$(form).find('.form-group').removeClass('focused');
					// Auto-hide after 8 seconds
					setTimeout(function () {
						if (toast) { toast.style.opacity = '0'; setTimeout(function(){ toast.style.display = 'none'; toast.style.opacity = '1'; }, 500); }
					}, 8000);
				})
				.catch(function (error) {
					// Error
					if (toast) {
						toast.className = 'contact-toast contact-toast-error';
						toast.innerHTML = '<span class="toast-icon">❌</span> Something went wrong. Please email me directly at <a href="mailto:csetanmaya.ai@gmail.com">csetanmaya.ai@gmail.com</a>';
						toast.style.display = 'flex';
					}
				})
				.finally(function () {
					// Reset button state
					btn.removeAttribute('disabled');
					if (btnText) btnText.style.display = 'inline';
					if (btnLoading) btnLoading.style.display = 'none';
				});
			});
        },

        
        
